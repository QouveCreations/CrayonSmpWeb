const fs = require('fs');
const path = require('path');
const { PNG } = require('pngjs');

// Parse the bbmodel
const bbmodelPath = path.resolve(__dirname, '../crayon_brush.bbmodel');
const configOutPath = path.resolve(__dirname, '../src/config/voxel-logo.config.js');

const rawData = fs.readFileSync(bbmodelPath, 'utf8');
const model = JSON.parse(rawData);

// Extract the base64 texture from the model
let base64Data = '';
if (model.textures && model.textures.length > 0) {
  const texture = model.textures[0];
  if (texture.source) {
    base64Data = texture.source.replace(/^data:image\/png;base64,/, '');
  } else if (texture.layers && texture.layers.length > 0) {
    base64Data = texture.layers[0].data_url.replace(/^data:image\/png;base64,/, '');
  }
}

if (!base64Data) {
  console.error("Could not find base64 texture in bbmodel");
  process.exit(1);
}

const buffer = Buffer.from(base64Data, 'base64');

new PNG().parse(buffer, function(error, data) {
  if (error) {
    console.error("Error parsing PNG data:", error);
    process.exit(1);
  }
  
  const voxels = [];
  const width = data.width;
  const height = data.height;

  // Center the voxels around (0,0)
  const offsetX = -Math.floor(width / 2);
  const offsetY = Math.floor(height / 2);

  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const idx = (width * y + x) << 2;
      const r = data.data[idx];
      const g = data.data[idx + 1];
      const b = data.data[idx + 2];
      const a = data.data[idx + 3];

      if (a > 0) {
        // Convert rgb to hex string
        const hex = "#" + (1 << 24 | r << 16 | g << 8 | b).toString(16).slice(1).toUpperCase();
        // y is inverted for 3D coordinates where Y is up
        voxels.push({
          position: [x + offsetX, offsetY - y, 0],
          color: hex
        });
      }
    }
  }

  const fileContent = `// AUTO-GENERATED FILE. DO NOT EDIT DIRECTLY.
// Generated by scripts/parse-bbmodel.js from crayon_brush.bbmodel

export const voxelLogoConfig = {
  voxels: ${JSON.stringify(voxels, null, 2)}
};
`;

  // Create src/config if it doesn't exist
  const configDir = path.dirname(configOutPath);
  if (!fs.existsSync(configDir)) {
    fs.mkdirSync(configDir, { recursive: true });
  }

  fs.writeFileSync(configOutPath, fileContent);
  console.log(`Successfully parsed bbmodel and generated ${voxels.length} voxels to src/config/voxel-logo.config.js`);
});
